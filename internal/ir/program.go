package ir

// Pos is a source location: a file relative to the project root and a
// 1-based line and column.
type Pos struct {
	File string
	Line int
	Col  int
}

// Program is a checked GoVibe program.
type Program struct {
	App      *App
	Auth     *Model // the account model, or nil without auth
	Models   []*Model
	Funcs    []*Func // top-level fns, including externs
	Features []*Feature
	Routes   []*Route // every route, generated ones included
}

// App holds the settings of the app block.
type App struct {
	Name  string
	Snake string // Name in snake_case: the binary and default database name
	DB    string // database URL, or "" for the default
	Pos   Pos
}

// Model is a model and the table that stores it.
type Model struct {
	Name   string
	Table  string
	Fields []*Field // id, created_at and updated_at first
	Pos    Pos
}

// Field returns the field called name, or nil.
func (m *Model) Field(name string) *Field {
	for _, f := range m.Fields {
		if f.Name == name {
			return f
		}
	}
	return nil
}

// Field is a model field.
type Field struct {
	Name     string
	Column   string // name, or name_id for a Ref
	Type     *Type  // the value type; a Ref holds an ID
	Ref      *Model // target of a Ref field
	Source   *Field // source field of a Slug field
	Unique   bool   // id, slugs and fields marked unique
	Min      *Const // bound on the length of Text, or on a number
	Max      *Const
	Default  *Const
	Implicit bool // id, created_at and updated_at, which are never writable
	Pos      Pos
}

// Required reports whether a create must give the field: it is written
// by the user, not optional, without a default and not a generated slug.
func (f *Field) Required() bool {
	return !f.Implicit && f.Type.Kind != Optional && f.Default == nil && f.Type.Kind != Slug
}

// Feature groups the functions and tests of one capability. Its routes are
// in Program.Routes.
type Feature struct {
	Name  string
	Funcs []*Func
	Tests []*Test
	Pos   Pos
}

// Func is a fn or an extern fn.
type Func struct {
	Name    string
	Params  []*Param
	Result  *Type
	Body    *Block // nil for an extern
	Extern  bool
	Feature string // "" for a top-level function
	Pos     Pos
}

// Test is a test block.
type Test struct {
	Name    string
	Feature string
	Body    *Block
	Pos     Pos
}

// Origin tells where a route comes from.
type Origin int

// Route origins.
const (
	FromRoute   Origin = iota // a get, post, patch or delete declaration
	FromCrud                  // expanded from crud
	FromAuth                  // generated by auth
	FromBuiltin               // GET /healthz
)

// Route is one HTTP endpoint.
type Route struct {
	Method  string // GET, POST, PATCH or DELETE
	Path    string // a net/http pattern path, such as /books/{id}
	Params  []*Param
	Result  *Type  // Empty when the route answers no body
	Status  string // success status: ok, created or empty
	Login   bool   // answers login_required without a session
	Origin  Origin
	Feature string

	// Value or Body is the code of a FromRoute route.
	Value Expr
	Body  *Block

	// Model, Op, Key, Owner and Private describe a FromCrud route; Op also
	// names a FromAuth route: register, login, logout or me.
	Model   *Model
	Op      string
	Key     *Field
	Owner   *Field
	Private bool

	Pos Pos
}

// Source tells where a route parameter comes from.
type Source int

// Parameter sources.
const (
	InPath Source = iota
	InQuery
	InBody
)

// Param is a parameter of a route or function.
type Param struct {
	Name    string
	Type    *Type
	In      Source
	Default *Const
	Var     *Var // the local the code reads; nil for generated routes
	Pos     Pos
}
